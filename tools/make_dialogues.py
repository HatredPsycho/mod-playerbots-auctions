#!/usr/bin/env python3
"""Turns data/dialogues.txt into src/PbaDialogues.cpp: the built-in auction conversations."""
import os
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "data", "dialogues.txt")
TARGET = os.path.join(ROOT, "src", "PbaDialogues.cpp")

rows = []
with open(SOURCE, encoding="utf-8") as source:
    for number, line in enumerate(source, 1):
        line = line.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        parts = line.split("|")
        if len(parts) != 4:
            raise SystemExit("line %d: expected id|step|personality|text" % number)
        ident, step, personality, text = (part.strip() for part in parts)
        if not ident.isdigit() or not step.isdigit():
            raise SystemExit("line %d: id and step must be numbers" % number)
        if not personality or not text or len(text) > 255 or any(ord(c) < 32 or ord(c) > 126 for c in text):
            raise SystemExit("line %d: text must be 1 to 255 plain ASCII characters" % number)
        rows.append((int(ident), int(step), personality, text))

# Every id must have 2 or 3 contiguous steps.
by_id = {}
for ident, step, personality, text in rows:
    by_id.setdefault(ident, []).append((step, personality, text))
for ident, steps in by_id.items():
    steps.sort()
    if len(steps) not in (2, 3) or [s[0] for s in steps] != list(range(len(steps))):
        raise SystemExit("dialogue %d: expected 2 or 3 steps numbered from 0" % ident)

rows.sort(key=lambda row: (row[0], row[1]))
version = zlib.crc32("\n".join("|".join(map(str, row)) for row in rows).encode()) or 1


def literal(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("??", "?\\?") + '"'


with open(TARGET, "w", encoding="utf-8", newline="\n") as out:
    out.write("// Generated by tools/make_dialogues.py from data/dialogues.txt. Do not edit.\n\n")
    out.write('#include "Pba.h"\n\nnamespace pba\n{\n')
    out.write("    uint32 const DialogueVersion = %du;\n" % version)
    out.write("    DialogueStep const Dialogues[] =\n    {\n")
    for ident, step, personality, text in rows:
        out.write("        { %d, %d, %s, %s },\n" % (ident, step, literal(personality), literal(text)))
    out.write("    };\n\n")
    out.write("    size_t const DialogueSize = sizeof(Dialogues) / sizeof(Dialogues[0]);\n")
    out.write("    uint32 const DialogueCount = %d;\n}\n" % len(by_id))
print("%d dialogues, %d lines, version %d" % (len(by_id), len(rows), version))
